import type { IconShape } from "./placement";
import type { IconMap } from "./store";

/**
 * Drawing the icons in the file explorer, without touching any file.
 *
 * The mechanism is a generated stylesheet rather than DOM injection, and that choice is the whole
 * design:
 *
 * - **Obsidian re-renders the file explorer constantly** — on expand, collapse, rename, sync, tab
 *   switch. Anything that inserts elements has to detect each of those and re-insert, which is the
 *   source of nearly every bug in file-explorer plugins.
 * - **CSS needs none of that.** One `<style>` element with a rule per note, and Obsidian's own
 *   re-render picks it up automatically. There is no observer, no bookkeeping, and nothing to
 *   clean up when the tree is rebuilt.
 *
 * Selector is the documented, long-standing shape
 * `.nav-file-title[data-path="…"] .nav-file-title-content::before` — `data-path` on the row is what
 * makes per-note targeting possible.
 *
 * The failure mode is deliberately quiet: if a future Obsidian renames that element, the selectors
 * simply stop matching. Notes lose an icon; nothing breaks.
 */

export const STYLE_ELEMENT_ID = "auto-icon-tree";

/** Which element carries the file name inside a file-explorer row. */
const ROW_SELECTOR = '.nav-file-title[data-path="%s"] .nav-file-title-content::before';

/** Escape a path for use inside a double-quoted CSS attribute selector. */
export function escapePath(path: string): string {
  return path.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

/**
 * Percent-encode an SVG so it can sit in a `url("data:…")`.
 *
 * `#` in particular would otherwise truncate the URL at the fragment and silently drop the rest of
 * the path data.
 */
export function svgDataUri(shape: IconShape): string {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${shape.viewBox}"><path d="${shape.d}"/></svg>`;
  return `data:image/svg+xml,${encodeURIComponent(svg)
    .replace(/'/g, "%27")
    .replace(/"/g, "%22")
    .replace(/</g, "%3C")
    .replace(/>/g, "%3E")
    .replace(/#/g, "%23")}`;
}

export interface BuildOptions {
  /** Resolves a note's mXn name + style to drawable path data. */
  shapeFor: (icon: string, style: string) => IconShape | null;
  /** CSS colour for the icon; defaults to the surrounding text colour. */
  color?: string;
}

/**
 * Build the stylesheet.
 *
 * Notes whose icon cannot be resolved are skipped rather than emitted as a broken rule, and the
 * count is returned so the caller can tell the user rather than leave them wondering why one note
 * has no icon.
 */
export function buildCss(map: IconMap, opts: BuildOptions): { css: string; skipped: string[] } {
  const skipped: string[] = [];
  const rules: string[] = [];

  for (const [path, assignment] of Object.entries(map)) {
    const shape = opts.shapeFor(assignment.icon, assignment.style);
    if (!shape) {
      skipped.push(path);
      continue;
    }
    const size = `${assignment.size}px`;
    rules.push(
      `${ROW_SELECTOR.replace("%s", escapePath(path))}{` +
        `content:url("${svgDataUri(shape)}");` +
        `width:${size};height:${size};` +
        `display:inline-block;vertical-align:-0.2em;` +
        `margin-inline-end:0.35em;` +
        (opts.color ? `color:${opts.color};` : "") +
        `}`
    );
  }

  return { css: rules.join("\n"), skipped };
}

/** The complete stylesheet, including the reset every rule relies on. */
export function wrapCss(rules: string): string {
  return [
    `/* Generated by Auto Icon — do not edit. Notes are never modified; this is display only. */`,
    `.nav-file-title .nav-file-title-content::before{margin-inline-end:0.35em;}`,
    rules,
  ].join("\n");
}

/**
 * Install or replace the stylesheet.
 *
 * One element, replaced wholesale. Re-generating on every change means there is never a stale rule
 * left pointing at a note that has since been re-categorised.
 */
export function applyStylesheet(doc: Document, css: string): HTMLStyleElement {
  let style = doc.getElementById(STYLE_ELEMENT_ID) as HTMLStyleElement | null;
  if (!style) {
    style = doc.createElement("style");
    style.id = STYLE_ELEMENT_ID;
    doc.head.appendChild(style);
  }
  style.textContent = css;
  return style;
}

export function removeStylesheet(doc: Document): void {
  doc.getElementById(STYLE_ELEMENT_ID)?.remove();
}